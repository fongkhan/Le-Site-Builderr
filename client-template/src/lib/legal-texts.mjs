/**
 * Texte `key` dans la langue `locale` (repli sur le français, puis sur la clé).
 * `vars` remplace les marqueurs {nom} (texte brut : Astro échappe au rendu).
 */
export function lt(locale, key, vars) {
  const dict = Object.hasOwn(LEGAL_TEXTS, locale) ? LEGAL_TEXTS[locale] : LEGAL_TEXTS.fr;
  let text = Object.hasOwn(dict, key) ? dict[key] : Object.hasOwn(LEGAL_TEXTS.fr, key) ? LEGAL_TEXTS.fr[key] : key;
  if (vars) text = text.replace(/\{(\w+)\}/g, (m, name) => (Object.hasOwn(vars, name) ? String(vars[name]) : m));
  return text;
}
